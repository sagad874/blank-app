def run_maf(code):
    msg("تشخيص MAF","ما نبدّل الحساس مباشرة؛ نستبعد الأسباب وحدة وحدة.")
    for n,(q,o) in enumerate(MAF,1):
        a=ask(n,q,o,f"{code}_m{n}")

        if n==2 and a=="لا":
            msg("افحص مسار الهواء","أصلح التسريب/الفلتر/اللي ثم أعد الاختبار.")

        elif n==3 and a=="لا":
            msg("خلل بالدائرة","أصلح الفيشة أو السلك ثم أعد الاختبار.")

        elif n==4 and a=="لا":
            msg("خلل محتمل بالتغذية","أصلح Power أو Ground ثم أعد القراءة.")

        elif n==5 and a=="لا، مو طبيعية":
            msg("القراءة منحرفة","ننتقل إلى Signal والدائرة والحساس.")

        elif n==5 and a=="ما عندي Live Data":
            msg("ما عندك Live Data؟ ما نوقف","نكمل بالفحص اليدوي والكهربائي.")

        elif n==6 and a=="لا":
            msg("سلوك القراءة غير طبيعي","ركز على Signal وPower وGround والدائرة.")

        elif n==7 and a=="إي":
            msg("احتمال دخول هوا","افحص مسار السحب بعد MAF.")

        elif n==8 and a=="إي":
            msg("أكو سبب مرتبط","شخّص الكود/العَرَض المصاحب قبل تبديل MAF.")

        elif n==9 and a=="لا":
            msg("الكود اختفى","راقب السيارة بظروف مختلفة.")
            break

        elif n==10 and a=="لا":
            msg("خلل بالدائرة","أصلح Signal/الأسلاك ثم أعد الاختبار.")

        elif n==11 and a=="لا":
            msg("Signal خارج المواصفات","افحص الحساس والدائرة حسب مواصفات الموديل.")

        elif n==12 and a=="إي":
            msg("الحساس مشتبه به","إذا الدائرة سليمة والاختبار يؤكد ذلك، استبدل القطعة الصحيحة.")

        elif n==13 and a=="إي":
            msg("تم حل العطل","القراءة رجعت طبيعية والكود اختفى.")
            break

        elif n==13 and a=="لا":
            msg("العطل مستمر","نرجع للدائرة وظروف التشغيل ووحدة التحكم حسب إجراء BYD.","warning")

