import streamlit as st

# إعدادات الصفحة
st.set_page_config(page_title="BYD Iraq Team", page_icon="🚗", layout="centered")

# العنوان الرئيسي
st.title("🚗 تطبيق فريق BYD العراق")
st.write("النسخة المتقدمة | حاسبة التوفير ودليل الأعطال الشامل")

st.markdown("---")

# --- 1. حاسبة التوفير الذكية عبر عداد السيارة ---
st.header("📊 حاسبة التوفير عبر عداد السيارة")
st.write("أدخل قراءة عداد السيارة (الكيلومترات) لحساب التوفير:")

col1, col2 = st.columns(2)
with col1:
    prev_km = st.number_input("قراءة العداد السابقة (كم):", value=10000, step=100)
with col2:
    current_km = st.number_input("قراءة العداد الحالية (كم):", value=11500, step=100)

if current_km > prev_km:
    total_km = current_km - prev_km
    
    # حساب التكلفة (تقدير متوسط العراق)
    cost_gasoline = (total_km / 10) * 1000  # بنزين
    cost_ev = (total_km / 6) * 50            # شحن كهربائي
    savings = cost_gasoline - cost_ev

    st.info(f"🛣️ المسافة المقطوعة: **{total_km:,} كم**")
    st.success(f"💰 التوفير المالي المحقق: **{int(savings):,} دينار عراقي**")
    
    with st.expander("تفاصيل المقارنة"):
        st.write(f"- تكلفة البنزين المقابلة: {int(cost_gasoline):,} دينار")
        st.write(f"- تكلفة الشحن الكهربائي: {int(cost_ev):,} دينار")
else:
    st.warning("يرجى التأكد من أن القراءة الحالية أكبر من القراءة السابقة.")

st.markdown("---")

# --- 2. دليل الأعطال الموسع مع الشرح والفيديو ---
