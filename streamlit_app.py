def step(no, text):

    st.markdown(
        f"""
        <div style="
            background:#222;
            color:white;
            padding:10px;
            border-radius:10px;
            text-align:center;
            font-size:22px;
            font-weight:bold;
            margin-top:18px;
            margin-bottom:10px;">
            الخطوة {no}
        </div>
        """,
        unsafe_allow_html=True
    )

    st.markdown(
        f"""
        <div style="
            direction:rtl;
            text-align:right;
            font-size:18px;
            padding:12px;
            border:1px solid #555;
            border-radius:10px;
            margin-bottom:10px;">
            🔧 {text}
        </div>
        """,
        unsafe_allow_html=True
    )


def result(title, text, kind="success"):

    msg = f"**{title}**\n\n{text}"

    if kind == "error":
        st.error(msg)

    elif kind == "warning":
        st.warning(msg)

    else:
        st.success(msg)


