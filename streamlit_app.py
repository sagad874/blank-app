# --- 5. البحث والاختيار ---

st.header("🔧 الموسوعة الميدانية الشاملة للأعطال (+100 كود)")

search_input = st.text_input("🔍 اكتب الكود للبحث المباشر (مثال: P0301, C1241, P0AA6, U0100):").strip()

selected_item = None

if search_input:
    matched = [k for k in db_codes.keys() if search_input.lower() in k.lower()]
    if matched:
        chosen_key = st.selectbox("📌 النتائج المطابقة للبحث:", matched)
        selected_item = db_codes[chosen_key]
    else:
        st.warning(f"لم نجد الكود ({search_input}) في القائمة.")
        st.markdown(f"[🔍 ابحث عن فيديو الصيانة لـ {search_input} مباشرة على يوتيوب](https://www.youtube.com/results?search_query=BYD+{search_input}+repair)")
else:
    options = ["اختر كود من القائمة..."] + list(db_codes.keys())
    chosen_key = st.selectbox("📌 اختر كود العطل من القائمة الشاملة:", options)
    if chosen_key != "اختر كود من القائمة...":
        selected_item = db_codes[chosen_key]

# --- 6. التشغيل التفاعلي للخطوات ---

if selected_item:
    st.markdown("---")
    st.subheader(selected_item["title"])
    st.error(selected_item["danger"])
    
    st.markdown("### 🛠️ شجرة التشخيص الميدانية التفاعلية:")

    # إدارة الانتقال بين العقد
    if "node" not in st.session_state or st.session_state.get("current_active_title") != selected_item["title"]:
        st.session_state.node = "step_1"
        st.session_state.current_active_title = selected_item["title"]

    curr_node = st.session_state.node

    # 1. حالة الأسئلة والاختيارات
    if curr_node in selected_item["steps"]:
        step_data = selected_item["steps"][curr_node]
        
        st.info(f"**{step_data['q']}**")
        
        user_opt = st.radio("حدد قراءة الفحص الميداني لديك:", list(step_data["options"].keys()))
        
        if st.button("تأكيد النتيجة والتالي ➡️"):
            st.session_state.node = step_data["options"][user_opt]
            st.rerun()

    # 2. حالة النتيجة والحل النهائي
    elif curr_node in selected_item["outcomes"]:
        res_text = selected_item["outcomes"][curr_node]
        
        if "✅" in res_text:
            st.success(res_text)
            st.balloons()
        elif "🛠️" in res_text:
            st.warning(res_text)
        else:
            st.error(res_text)

        st.markdown("<br>", unsafe_allow_html=True)
        if st.button("🔄 إعادة تشخيص هذا الكود من الخطوة الأولى"):
            st.session_state.node = "step_1"
            st.rerun()

    # رابط يوتيوب المباشر
    st.markdown("---")
    c_only = selected_item["code_only"]
    d_only = selected_item["desc_only"]
    yt_url = f"https://www.youtube.com/results?search_query=BYD+{c_only}+{d_only.replace(' ', '+')}"
    st.markdown(f"🎥 **[اضغط هنا لمشاهدة فيديو شرح ميداني لـ {c_only} على يوتيوب]({yt_url})**")

st.markdown("---")
st.caption("إهداء خاص إلى قائد وأعضاء فريق BYD العراق ❤️")
