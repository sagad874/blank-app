                "**الخطوة 2: تحديد مكان محول الـ DC-DC:** هو صندوق ألمنيوم مربّع تحت البونيد بجانب عقل السيارة الرئيسي تخرج منه أسلاك غليظة.",
                "**الخطوة 3: فحص الفيوزات الكبيرة:** افتح علبة الفيوزات المجاورة للبطارية وتأكد أن الفيوز الرئيسي للـ DC-DC غير محترق.",
                "**الخطوة 4: فحص فيشة الاتصال (CAN-Bus):** افصل الفيشة الصغيرة الموصولة بصندوق المحول، ونظف أسنادها الداخلية ثم أعد تركيبها بإحكام."
