                "**الخطوة 1: فحص بطارية الـ 12V أولاً:** افتح غطاء المحرك الأمامي (البونيد). افحص قطبي البطارية الصغيرة. إذا كان هناك كلس أبيض متراكم، اسكب عليه ماء حار قليلاً ونظفه بفرشاة سلكية.",
