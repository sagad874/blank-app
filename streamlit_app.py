def diagnose(code):

    # ╔══════════════════════════════════════════╗
    # P0AA6
    # ╚══════════════════════════════════════════╝

    if code == "P0AA6":

        st.subheader("P0AA6 — تسريب عزل الجهد العالي")

        st.error(
            "🚨 تنبيه مهم: هذا الكود يخص منظومة الجهد العالي. "
            "لا تلمس الأسلاك البرتقالية ولا تفتح أجزاء HV "
            "إلا إذا عندك معدات السلامة وإجراء BYD الخاص بالسيارة."
        )

        step(
            1,
            "أكو أكواد ثانية طالعة ويا P0AA6؟"
        )

        a = st.radio(
            "شنو النتيجة؟",
            ["إي، أكو", "لا، ماكو"],
            key="p0aa6_1"
        )

        if a == "إي، أكو":
            result(
                "ابدأ بالكود المصاحب",
                "إذا أكو كود ثاني ويا P0AA6، شخّص الكود المصاحب أولاً؛ "
                "لأن ممكن هو اللي يحدد أي جزء من منظومة HV بيه المشكلة.",
                "warning"
            )
            return

        step(
            2,
            "العطل ظهر بعد غسيل، دخول مي، حادث، أو شغل صيانة؟"
        )

        b = st.radio(
            "شنو النتيجة؟",
            ["إي", "لا"],
            key="p0aa6_2"
        )

        if b == "إي":
            result(
                "مسار الرطوبة أو الضرر",
                "هنا ركّز على احتمال دخول مي أو حدوث ضرر أثناء الصيانة. "
                "فحص منظومة HV لازم يصير حسب إجراء BYD الخاص بالموديل.",
                "warning"
            )
            return

        step(
            3,
            "من تمسح الكود، يرجع مباشرة؟"
        )

        c = st.radio(
            "شنو النتيجة؟",
            ["إي، يرجع فوراً", "لا، ما يرجع"],
            key="p0aa6_3"
        )

        if c == "إي، يرجع فوراً":
            result(
                "العطل بعده موجود",
                "هذا يدل إن المشكلة مو مجرد كود قديم. "
                "لا تبدّل أي قطعة عشوائياً؛ لازم فحص عزل HV بالطريقة المعتمدة.",
                "error"
            )
        else:
            result(
                "العطل متقطع",
                "سجّل متى يظهر الكود وتحت أي ظروف، وراقب إذا يرجع مرة ثانية. "
                "اختفاء الكود وحده ما يعني أن السبب انحل."
            )

        return


    # ╔══════════════════════════════════════════╗
    # U0298
    # ╚══════════════════════════════════════════╝

    if code == "U0298":

        st.subheader("U0298 — فقدان الاتصال ويا DC/DC")

        step(
            1,
            "أكو أكواد U ثانية أو أكواد تخص بطارية 12V؟"
        )

        a = st.radio(
            "شنو النتيجة؟",
            ["إي، أكو", "لا، ماكو"],
            key="u0298_1"
        )

        if a == "إي، أكو":
            result(
                "ابدأ بالأكواد المصاحبة",
                "وجود أكثر من كود اتصال ممكن يغيّر اتجاه التشخيص، "
                "فلا نعتمد على U0298 وحده.",
                "warning"
            )
            return

        step(
            2,
            "بطارية الـ12V وفولتية التغذية مالها ضمن الطبيعي؟"
        )

        b = st.radio(
            "شنو النتيجة؟",
            ["إي، طبيعية", "لا، ضعيفة", "ما أدري"],
            key="u0298_2"
        )

        if b == "لا، ضعيفة":
            result(
                "ابدأ من بطارية 12V",
                "عالج مشكلة بطارية 12V أو تغذيتها أولاً، "
                "وبعدها امسح الأكواد وأعد الفحص."
            )
            return

        if b == "ما أدري":
            result(
                "افحص 12V أولاً",
                "قبل لا نحكم على DC/DC، لازم نتأكد من بطارية 12V "
                "والتغذية والأرضي حسب مواصفات السيارة.",
                "warning"
            )
            return

        step(
            3,
            "فيوزات وتغذية الـDC/DC سليمة؟"
        )

        c = st.radio(
            "شنو النتيجة؟",
            ["إي، سليمة", "لا، بيها مشكلة"],
            key="u0298_3"
        )

        if c == "لا، بيها مشكلة":
            result(
                "روح لمسار التغذية",
                "افحص الفيوزات والتغذية والأسلاك المرتبطة بالـDC/DC "
                "حسب مخطط السيارة."
            )
            return

        step(
            4,
            "التغذية سليمة، بس بعده ماكو اتصال ويا وحدة DC/DC؟"
        )

        d = st.radio(
            "شنو النتيجة؟",
            ["إي، ماكو اتصال", "لا، الاتصال موجود"],
            key="u0298_4"
        )

        if d == "إي، ماكو اتصال":
            result(
                "روح لمسار CAN",
                "هنا ننتقل لفحص شبكة CAN والفيش والأسلاك والوحدة نفسها "
                "حسب مخطط BYD.",
                "warning"
            )
        else:
            result(
                "نحتاج معلومات أكثر",
                "راجع الأكواد الحالية وبيانات Live Data قبل لا تبدّل أي قطعة.",
                "warning"
            )

        return


    # ╔══════════════════════════════════════════╗
    # أكواد MAF
    # ╚══════════════════════════════════════════╝

    if code in ["P0100", "P0101", "P0102", "P0103"]:

        st.subheader(f"{code} — حساس MAF")

        step(
            1,
            "أكو أكواد ثانية تخص المحرك طالعة ويا هذا الكود؟"
        )

        a = st.radio(
            "شنو النتيجة؟",
            ["إي، أكو", "لا، ماكو"],
            key=f"{code}_1"
        )

        if a == "إي، أكو":
            result(
                "شخّص الأكواد المصاحبة أولاً",
                "ممكن الكود الثاني يكون هو السبب والكود الحالي مجرد نتيجة."
            )
            return

        step(
            2,
            "فيشة حساس MAF والأسلاك مالته شكلها سليم؟"
        )

        b = st.radio(
            "شنو النتيجة؟",
            ["إي، سليمة", "لا، بيها مشكلة"],
            key=f"{code}_2"
        )

        if b == "لا، بيها مشكلة":
            result(
                "ابدأ من الفيشة والأسلاك",
                "صلّح مشكلة الفيشة أو الأسلاك أولاً، وبعدها أعد الفحص."
            )
            return

        step(
            3,
            "قراءة MAF ببيانات Live Data طبيعية؟"
        )

        c = st.radio(
            "شنو النتيجة؟",
            ["إي، طبيعية", "لا، مو طبيعية", "ما أدري"],
            key=f"{code}_3"
        )

        if c == "إي، طبيعية":
            result(
                "لا تستعجل وتبدّل الحساس",
                "إذا قراءة MAF منطقية، لا تعتبر الحساس خربان لمجرد وجود الكود. "
                "كمّل البحث عن سبب ثاني."
            )

        elif c == "لا، مو طبيعية":
            result(
                "كمّل بفحص دائرة MAF",
                "افحص التغذية والأرضي والإشارة والأسلاك حسب مخطط السيارة."
            )

        else:
            result(
                "نحتاج Live Data",
                "افتح بيانات Live Data وخذ قراءة MAF وقارنها بالمواصفات "
                "الخاصة بالسيارة.",
                "warning"
            )

        return


    # ╔══════════════════════════════════════════╗
    # جميع أكواد U
    # ╚══════════════════════════════════════════╝

    if code.startswith("U"):

        st.subheader(f"{code} — مشكلة اتصال بين وحدات السيارة")

        step(
            1,
            "أكو أكواد U ثانية طالعة ويا هذا الكود؟"
        )

        a = st.radio(
            "شنو النتيجة؟",
            ["إي، أكو", "لا، ماكو"],
            key=f"{code}_u1"
        )

        if a == "إي، أكو":
            result(
                "افحص شبكة الاتصال أولاً",
                "إذا أكثر من وحدة فقدت الاتصال، ممكن المشكلة مشتركة "
                "بالتغذية أو شبكة CAN.",
                "warning"
            )
            return

        step(
            2,
            "الوحدة اللي فقدت الاتصال واصلها Power وGround بشكل صحيح؟"
        )

        b = st.radio(
            "شنو النتيجة؟",
            ["إي، واصل", "لا، مو واصل", "ما أدري"],
            key=f"{code}_u2"
        )

        if b == "لا، مو واصل":
            result(
                "ابدأ من التغذية",
                "افحص الفيوز والتغذية والأرضي حسب مخطط السيارة."
            )
            return

        if b == "ما أدري":
            result(
                "تأكد من Power وGround",
                "لا تحكم على الوحدة ولا تبدّلها قبل ما تتأكد من التغذية والأرضي.",
                "warning"
            )
            return

        step(
            3,
            "فقدان الاتصال يصير ويرجع، يعني متقطع؟"
        )

        c = st.radio(
            "شنو النتيجة؟",
            ["إي، متقطع", "لا، ثابت"],
            key=f"{code}_u3"
        )

        if c == "إي، متقطع":
            result(
                "فتّش عن مشكلة اتصال متقطعة",
                "ركّز على الفيش والأسلاك وشبكة CAN، خصوصاً إذا العطل يظهر "
                "ويختفي حسب حركة السيارة أو الظروف."
            )
        else:
            result(
                "فقدان اتصال ثابت",
                "انتقل لفحص CAN والتغذية والوحدة حسب مخطط السيارة وإجراء المصنع."
            )

        return


    # ╔══════════════════════════════════════════╗
    # المسار العام المتدرج
    # ╚══════════════════════════════════════════╝

    st.subheader(
        f"{code} — {codes.get(code, 'كود تشخيصي')}"
    )

    # ───── الخطوة 1 ─────

    step(
        1,
        "أكو كود ثاني مرتبط بنفس النظام؟"
    )

    a = st.radio(
        "شنو النتيجة؟",
        ["إي، أكو", "لا، ماكو"],
        key=f"{code}_g1"
    )

    if a == "إي، أكو":
        result(
            "ابدأ بالكود المصاحب",
            "الكود المصاحب ممكن يوضح السبب أكثر من الكود الحالي، "
            "فشخّصه أولاً وبعدين ارجع لهذا الكود إذا بقى موجود.",
            "warning"
        )
        return


    # ───── الخطوة 2 ─────

    step(
        2,
        "العطل موجود هسه لو الكود مجرد مسجل من قبل؟"
    )

    b = st.radio(
        "شنو النتيجة؟",
        ["العطل موجود هسه", "الكود قديم فقط"],
        key=f"{code}_g2"
    )

    if b == "الكود قديم فقط":
        result(
            "راقب العطل",
            "امسح الكود حسب الإجراء المناسب، وبعدها جرّب السيارة "
            "وشوف إذا يرجع الكود مرة ثانية."
        )
        return


    # ───── الخطوة 3 ─────

    step(
        3,
        "الفيوزات والتغذية الكهربائية المرتبطة بالنظام سليمة؟"
    )

    c = st.radio(
        "شنو النتيجة؟",
        ["إي، سليمة", "لا، بيها مشكلة"],
        key=f"{code}_g3"
    )

    if c == "لا، بيها مشكلة":
        result(
            "ابدأ من التغذية",
            "صلّح الفيوز أو مشكلة التغذية أولاً، وبعدها امسح الكود "
            "وأعد الفحص."
        )
        return


    # ───── الخطوة 4 ─────

    step(
        4,
        "الفيشة والأسلاك مال القطعة المرتبطة بالكود شكلها سليمة؟"
    )

    d = st.radio(
        "شنو النتيجة؟",
        ["إي، سليمة", "لا، بيها مشكلة"],
        key=f"{code}_g4"
    )

    if d == "لا، بيها مشكلة":
        result(
            "ابدأ من الفيشة والأسلاك",
            "فتّش عن قطع، تأكسد، ارتخاء، رطوبة أو احتكاك بالأسلاك. "
            "صلّح المشكلة وبعدها أعد الفحص."
        )
        return


    # ───── الخطوة 5 ─────

    step(
        5,
        "أكو شي غير طبيعي بأعراض السيارة مرتبط بهذا الكود؟"
    )

    e = st.radio(
        "شنو النتيجة؟",
        ["إي، أكو أعراض", "لا، السيارة طبيعية"],
        key=f"{code}_g5"
    )

    if e == "إي، أكو أعراض":
        result(
            "نحدد العطل من الأعراض",
            "سجّل شنو تسوي السيارة بالضبط: تقطيع، ضعف، عدم تشغيل، "
            "تحذير، حرارة، فقدان شحن أو غيرها. "
            "الأعراض تساعد بتحديد الفرع الصحيح بدل تبديل القطع عشوائياً."
        )
        return


    # ───── الخطوة 6 ─────

    step(
        6,
        "إذا تمسح الكود، يرجع مباشرة لو يحتاج تشغيل وتجربة حتى يرجع؟"
    )

    f = st.radio(
        "شنو النتيجة؟",
        ["يرجع مباشرة", "يرجع بعد التجربة", "ما يرجع"],
        key=f"{code}_g6"
    )

    if f == "ما يرجع":
        result(
            "العطل ممكن يكون متقطع",
            "لا تبدّل أي قطعة حالياً. راقب السيارة وشوف إذا يرجع الكود "
            "بنفس الظروف."
        )
        return

    if f == "يرجع بعد التجربة":
        result(
            "ركز على ظروف ظهور العطل",
            "لاحظ متى يرجع الكود: عند التشغيل، التسارع، الفرملة، "
            "الشحن، تشغيل المكيف أو بعد ارتفاع الحرارة."
        )
        return


    # ───── الخطوة 7 ─────

    step(
        7,
        "إذا عندك جهاز فحص، بيانات Live Data بيها قراءة غير طبيعية؟"
    )

    g = st.radio(
        "شنو النتيجة؟",
        ["إي، القراءة غير طبيعية", "لا، القراءة طبيعية", "ما عندي Live Data"],
        key=f"{code}_g7"
    )

    if g == "إي، القراءة غير طبيعية":
        result(
            "لقينا مسار للفحص",
            "القراءة غير الطبيعية تعطينا اتجاه أوضح. "
            "قارنها بمواصفات السيارة قبل الحكم على القطعة."
        )
        return

    if g == "ما عندي Live Data":
        result(
            "نكمل بالفحص اليدوي",
            "عدم توفر Live Data مو معناه نوقف التشخيص. "
            "نكمل بالفحص اليدوي ومراقبة الأعراض ورجوع الكود."
        )
        return


    # ───── الخطوة 8 ─────

    step(
        8,
        "بعد كل الفحوصات السابقة، الكود بعده يرجع؟"
    )

    h = st.radio(
        "شنو النتيجة؟",
        ["إي، بعده يرجع", "لا، اختفى"],
        key=f"{code}_g8"
    )

    if h == "لا، اختفى":
        result(
            "المشكلة انحلت مبدئياً",
            "جرّب السيارة وتأكد أن الكود ما يرجع مرة ثانية. "
            "إذا بقى مختفي، لا تبدّل أي قطعة بدون سبب."
        )
        return


    # ───── آخر مرحلة فقط ─────

    result(
        "هنا وصلنا للفحص المتخصص",
        "وصلنا لهذي المرحلة بعد ما فحصنا الأكواد المصاحبة، "
        "والتغذية، والفيوزات، والفيش، والأسلاك، والأعراض، "
        "وطريقة رجوع الكود وبيانات Live Data. "
        "هنا يصير منطقي نستخدم مخطط النظام أو اختبار الوحدة "
        "أو القياسات الخاصة بهذا العطل.",
        "warning"
    )


