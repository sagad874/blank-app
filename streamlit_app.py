                "**الخطوة 3: عزل وتنظيف مكان التسريب:** إذا وجدت رطوبة أو أوساخ متراكمة حول فيش الكمبريسور أو بطارية الهايبิด، نظفها بماء مقطر ثم جففها تماماً ببخاخ تنظيف الإلكترونيات.",
