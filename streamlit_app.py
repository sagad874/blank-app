# --- 5. قوائم البحث والانتخاب ---
st.header("🔧 الموسوعة الميدانية الشاملة للأعطال")

search_query = st.text_input("🔍 اكتب الكود يدوياً بشكل مباشر (مثال: P0AA6, P0100, C1241):").strip()

chosen_data = None

if search_query:
    filtered_keys = [k for k in workshop_db.keys() if search_query.lower() in k.lower()]
    if filtered_keys:
        selected_code = st.selectbox("📌 النتائج المطابقة للبحث:", filtered_keys)
        chosen_data = workshop_db[selected_code]
    else:
        st.warning(f"لم نجد الكود ({search_query}) بالنظام الميداني.")
        st.markdown(f"[🔍 ابحث عن الشرح الميداني لـ {search_query} مباشرة على يوتيوب](https://www.youtube.com/results?search_query=BYD+{search_query}+repair+guide)")
else:
    options = ["اختر كود من القائمة..."] + list(workshop_db.keys())
    selected_code = st.selectbox("📌 اختر كود العطل من القائمة الميدانية الشاملة (+100 كود):", options)
    if selected_code != "اختر كود من القائمة...":
        chosen_data = workshop_db[selected_code]

# --- 6. العرض التفاعلي للخطوات بدون تداخل لغوي ---
if chosen_data:
    st.markdown("---")
    st.subheader(chosen_data["title"])
    st.error(chosen_data["danger"])
    
    st.markdown("### 🛠️ خطوات التصليح الميدانية:")

    steps = chosen_data["steps"]
    total_steps = len(steps)

    # تتبع الخطوة الحالية لكل كود
    if "step_index" not in st.session_state or st.session_state.get("current_title") != chosen_data["title"]:
        st.session_state.step_index = 0
        st.session_state.current_title = chosen_data["title"]

    idx = st.session_state.step_index

    # شريط التتبع والتقدم
    st.progress((idx + 1) / total_steps)
    
    # عرض رقم الخطوة ونشاطها بشكل مفصل وبدون أي رموز إنجليزية تعكس النص
    st.markdown(f"#### 📍 الخطوة رقم {idx + 1} من أصل {total_steps}")
    st.info(steps[idx])

    # أزرار التنقل التفاعلية
    col_prev, col_next = st.columns(2)
    
    with col_prev:
        if idx > 0:
            if st.button("السابقة ⬅️"):
                st.session_state.step_index -= 1
                st.rerun()

    with col_next:
        if idx < total_steps - 1:
            if st.button("الخطوة التالية ➡️"):
                st.session_state.step_index += 1
                st.rerun()
        else:
            if st.button("✅ إتمام الصيانة ومسح الكود"):
                st.balloons()
                st.success("تم إكمال كافة خطوات التصليح بنجاح! يمكنك الآن مسح الأكواد بـ OBD2.")

    # إعادة الضبط للبدء من جديد
    if st.button("🔄 إعادة البدء من الخطوة الأولى"):
        st.session_state.step_index = 0
        st.rerun()

    # عرض الفيديو التوضيحي
    if chosen_data.get("video"):
        st.markdown("---")
        st.write("🎥 **فيديو توضيحي تفصيلي من الورشة الميدانية:**")
        if "watch?v=" in chosen_data["video"]:
            st.video(chosen_data["video"])
        else:
            st.markdown(f"[▶️ اضغط هنا لمشاهدة فيديو صيانة هذا العطل على يوتيوب]({chosen_data['video']})")

st.markdown("---")
st.caption("إهداء خاص إلى قائد وأعضاء فريق BYD العراق ❤️ - صُمم ليكون دليلك الميداني الأول في الكراج")
