def diagnose_maf(code):

    result(
        "تشخيص MAF",
        "لا تبدّل الحساس مباشرة. نمشي من الأبسط إلى الأعمق."
    )

    d = ask(
        1,
        "أكو أكواد محرك ثانية ويا كود MAF؟",
        [
            "إي، أكو",
            "لا، ماكو",
            "ما متأكد"
        ],
        f"{code}_maf1"
    )

    if d == "إي، أكو":

        result(
            "الأكواد المصاحبة مهمة",
            "سجّل الأكواد الثانية وشخّصها أيضاً، لأن مشكلة ثانية ممكن تسبب كود MAF."
        )

    d2 = ask(
        2,
        "مسار الهواء والفلتر والليّات قبل وبعد MAF سليمة؟",
        [
            "إي، سليمة",
            "لا، أكو مشكلة",
            "ما متأكد"
        ],
        f"{code}_maf2"
    )

    if d2 == "لا، أكو مشكلة":

        result(
            "لقينا احتمال واضح",
            "أصلح دخول الهوا أو اللي أو الفلتر وبعدها أعد الفحص."
        )

        d3 = ask(
            3,
            "بعد الإصلاح، قراءة MAF صارت طبيعية؟",
            [
                "إي",
                "لا"
            ],
            f"{code}_maf3_repair"
        )

        if d3 == "إي":

            d4 = ask(
                4,
                "بعد مسح الكود وتجربة السيارة، يرجع الكود؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf4_repair"
            )

            if d4 == "لا":
                result(
                    "تم حل المشكلة",
                    "السبب كان بمسار الهواء والكود اختفى."
                )
                return

            result(
                "الكود رجع",
                "نكمّل بفحص دائرة MAF."
            )

    d5 = ask(
        3,
        "فيشة MAF والأسلاك ظاهرياً سليمة؟",
        [
            "إي",
            "لا",
            "ما متأكد"
        ],
        f"{code}_maf3_wire"
    )

    if d5 == "لا":

        result(
            "مشكلة بالدائرة",
            "أصلح الفيشة أو السلك المتضرر وبعدها أعد الاختبار."
        )

        d6 = ask(
            4,
            "بعد الإصلاح، القراءة رجعت طبيعية؟",
            [
                "إي",
                "لا"
            ],
            f"{code}_maf4_wire"
        )

        if d6 == "إي":

            d7 = ask(
                5,
                "بعد مسح الكود وتجربة السيارة، يرجع؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf5_wire"
            )

            if d7 == "لا":
                result(
                    "تم حل المشكلة",
                    "العطل كان بالدائرة."
                )
                return

            result(
                "الكود رجع",
                "ننتقل إلى Power وGround وSignal."
            )

    live = ask(
        4,
        "قراءة MAF بـ Live Data طبيعية؟",
        [
            "إي، طبيعية",
            "لا، مو طبيعية",
            "ما عندي Live Data"
        ],
        f"{code}_maf_live"
    )

    # -----------------------------------------------------
    # Live Data طبيعية
    # -----------------------------------------------------

    if live == "إي، طبيعية":

        result(
            "قراءة MAF حالياً طبيعية",
            "هذا ما يعني أن المشكلة انتهت. نختبر سلوك القراءة أثناء التشغيل."
        )

        a = ask(
            5,
            "قراءة MAF تتغير بصورة منطقية ويا RPM والحمل؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf5_normal"
        )

        if a == "لا":

            result(
                "السلوك غير طبيعي",
                "نركز على Signal وPower وGround والدائرة."
            )

        else:

            b = ask(
                6,
                "أكو احتمال دخول هوا بعد MAF؟",
                [
                    "إي",
                    "لا",
                    "ما متأكد"
                ],
                f"{code}_maf6_intake"
            )

            if b == "إي":

                result(
                    "افحص مسار السحب",
                    "أي هوا يدخل بعد MAF ممكن يخلي حساب الهواء غير صحيح."
                )

            c = ask(
                7,
                "أكو أعراض أو أكواد مرتبطة بخليط الوقود أو أداء المحرك؟",
                [
                    "إي",
                    "لا",
                    "ما متأكد"
                ],
                f"{code}_maf7_mix"
            )

            if c == "إي":

                result(
                    "نوسّع التشخيص",
                    "افحص الأكواد والأعراض المرتبطة قبل الحكم على MAF."
                )

            e = ask(
                8,
                "بعد مسح الكود وتجربة السيارة، يرجع الكود؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf8_normal"
            )

            if e == "لا":

                result(
                    "العطل غير ظاهر حالياً",
                    "راقب السيارة بظروف تشغيل مختلفة."
                )
                return

            result(
                "الكود رجع رغم القراءة الطبيعية",
                "نحتاج فحص العطل المتقطع والدائرة."
            )

        p = ask(
            9,
            "Power وGround مال MAF مطابقين للمواصفات؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf9_normal"
        )

        if p == "لا":

            result(
                "خلل بالتغذية أو الأرضي",
                "أصلح الدائرة وأعد الاختبار."
            )

        elif p == "إي":

            s = ask(
                10,
                "Signal والأسلاك بين MAF ووحدة التحكم سليمة؟",
                [
                    "إي",
                    "لا",
                    "ما متأكد"
                ],
                f"{code}_maf10_normal"
            )

            if s == "لا":

                result(
                    "خلل بالدائرة",
                    "أصلح السلك أو الفيشة وأعد الاختبار."
                )

            else:

                result(
                    "الدائرة تبدو سليمة",
                    "إذا القراءة طبيعية والدائرة سليمة والكود مستمر، نراجع ظروف تسجيل الكود وإجراء BYD للموديل.",
                    "warning"
                )

        else:

            result(
                "القياس غير مكتمل",
                "لا نحكم على الحساس بدون قياسات مؤكدة."
            )


    # -----------------------------------------------------
    # Live Data غير طبيعية
    # -----------------------------------------------------

    elif live == "لا، مو طبيعية":

        result(
            "لقينا انحراف بالقراءة",
            "ما نبدّل MAF مباشرة. نحدد هل السبب تغذية أو Ground أو Signal أو أسلاك أو مسار هوا."
        )

        power = ask(
            5,
            "Power وGround مال MAF صحيحين؟",
            [
                "إي، صحيحين",
                "لا، بيهم مشكلة",
                "ما متأكد"
            ],
            f"{code}_maf_power"
        )

        if power == "لا، بيهم مشكلة":

            result(
                "المشكلة ممكن من التغذية",
                "صلّح Power أو Ground وبعدها أعد قراءة MAF."
            )

            after = ask(
                6,
                "بعد إصلاح التغذية، قراءة MAF رجعت طبيعية؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf_after_power"
            )

            if after == "إي":

                again = ask(
                    7,
                    "بعد مسح الكود وتجربة السيارة، يرجع؟",
                    [
                        "إي",
                        "لا"
                    ],
                    f"{code}_maf_again_power"
                )

                if again == "لا":

                    result(
                        "تم حل المشكلة",
                        "التغذية أو الأرضي كانت سبب الخلل."
                    )
                    return

                result(
                    "الكود رجع",
                    "ننتقل لفحص Signal والأسلاك."
                )

            else:

                result(
                    "القراءة بعدها غير طبيعية",
                    "التغذية وحدها ما حلت المشكلة."
                )

        signal = ask(
            8,
            "إشارة MAF والأسلاك بين الحساس ووحدة التحكم سليمة؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf_signal"
        )

        if signal == "لا":

            result(
                "لقينا مشكلة بالدائرة",
                "أصلح السلك أو الفيشة وبعدها أعد الاختبار."
            )

            repaired = ask(
                9,
                "بعد الإصلاح، قراءة MAF رجعت طبيعية؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf_signal_repair"
            )

            if repaired == "إي":

                again = ask(
                    10,
                    "بعد مسح الكود وتجربة السيارة، يرجع؟",
                    [
                        "إي",
                        "لا"
                    ],
                    f"{code}_maf_signal_again"
                )

                if again == "لا":

                    result(
                        "تم حل المشكلة",
                        "الخلل كان بالدائرة."
                    )
                    return

            else:

                result(
                    "القراءة بعدها غير طبيعية",
                    "نكمل بفحص Signal والحساس."
                )

        spec = ask(
            11,
            "قيمة Signal نفسها ضمن مواصفات الموديل؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf_signal_spec"
        )

        if spec == "لا":

            result(
                "Signal خارج المواصفات",
                "الحساس أو دائرة القياس مشتبه بها. تأكد من طريقة القياس قبل تبديل القطعة."
            )

            sensor = ask(
                12,
                "بعد استبعاد Power وGround والأسلاك، الخلل يتبع الحساس نفسه؟",
                [
                    "إي",
                    "لا",
                    "ما متأكد"
                ],
                f"{code}_maf_sensor"
            )

            if sensor == "إي":

                result(
                    "الحساس صار المتهم الرئيسي",
                    "إذا إجراء BYD للموديل يؤكد أن الحساس خارج المواصفات بعد استبعاد الدائرة، يتم استبداله بالقطعة الصحيحة."
                )

                verify = ask(
                    13,
                    "بعد استبدال MAF، القراءة صارت طبيعية والكود اختفى؟",
                    [
                        "إي",
                        "لا"
                    ],
                    f"{code}_maf_verify"
                )

                if verify == "إي":

                    result(
                        "تم حل العطل",
                        "الحساس كان سبب المشكلة."
                    )

                else:

                    result(
                        "العطل مستمر",
                        "لا نعتبر MAF السبب الوحيد. نرجع للدائرة وظروف التشغيل ووحدة التحكم."
                    )

            elif sensor == "لا":

                result(
                    "المشكلة مو من الحساس وحده",
                    "نرجع لفحص الدائرة ومخطط السيارة."
                )

            else:

                result(
                    "النتيجة غير مؤكدة",
                    "لا تبدّل القطعة قبل الحصول على قياس مؤكد."
                )

        elif spec == "إي":

            result(
                "Signal ضمن المواصفات",
                "إذا Signal طبيعية رغم وجود الكود، نبحث عن سبب تسجيل الكود خارج الحساس."
            )

            condition = ask(
                12,
                "الكود يرجع فقط بظرف معين؟",
                [
                    "إي",
                    "لا، عشوائي",
                    "ما متأكد"
                ],
                f"{code}_maf_condition"
            )

            if condition == "إي":

                result(
                    "العطل مرتبط بظرف تشغيل",
                    "سجل RPM والحمل ودرجة الحرارة ووقت ظهور الكود."
                )

                repeat = ask(
                    13,
                    "عند إعادة نفس الظرف، هل Signal تتغير بشكل غير طبيعي؟",
                    [
                        "إي",
                        "لا",
                        "ما متأكد"
                    ],
                    f"{code}_maf_condition_repeat"
                )

                if repeat == "إي":

                    result(
                        "الخلل يظهر تحت الحمل أو الظرف المحدد",
                        "ركز على الدائرة ومسار السحب أثناء نفس الظرف."
                    )

                else:

                    result(
                        "الإشارة تبقى طبيعية",
                        "راجع الأكواد المصاحبة وإجراء التشخيص الخاص بالموديل."
                    )

            elif condition == "لا، عشوائي":

                result(
                    "احتمال عطل متقطع",
                    "ركز على الفيشة والأسلاك والرطوبة والاهتزاز وظروف ظهور الكود."
                )

                again = ask(
                    13,
                    "تقدر تراقب Live Data أثناء فحص الضفيرة والفيشة؟",
                    [
                        "إي",
                        "لا"
                    ],
                    f"{code}_maf_intermittent"
                )

                if again == "إي":

                    result(
                        "نستمر بفحص العطل المتقطع",
                        "أي تغير بالقراءة أثناء الفحص يساعد بتحديد مكان الخلل."
                    )

                else:

                    result(
                        "نحتاج قياس أدق",
                        "استخدم مخطط الدائرة وإجراء BYD المناسب للموديل."
                    )

            else:

                result(
                    "ظروف العطل غير واضحة",
                    "حدد ظروف تسجيل الكود قبل استبدال أي قطعة."
                )

        else:

            result(
                "القياس غير مؤكد",
                "نحتاج قيمة Signal المرجعية حسب موديل السيارة قبل الحكم على الحساس."
            )


    # -----------------------------------------------------
    # ماكو Live Data
    # -----------------------------------------------------

    else:

        result(
            "ما عندك Live Data؟ ما نوقف",
            "نكمل بالفحص اليدوي ونحدد إذا الكود ثابت أو متقطع."
        )

        manual = ask(
            5,
            "مسار السحب والفيشة والأسلاك سليمة بالفحص اليدوي؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf_manual"
        )

        if manual == "لا":

            result(
                "لقينا مشكلة محتملة",
                "أصلحها وبعدها امسح الكود وأعد التجربة."
            )

            repaired = ask(
                6,
                "بعد الإصلاح، الكود رجع؟",
                [
                    "إي",
                    "لا"
                ],
                f"{code}_maf_manual_repair"
            )

            if repaired == "لا":

                result(
                    "تم حل المشكلة",
                    "العطل اختفى بعد إصلاح المشكلة التي تم العثور عليها."
                )
                return

            result(
                "الكود رجع",
                "نكمّل بالفحص الكهربائي."
            )

        symptom = ask(
            7,
            "أكو أعراض بالمحرك مثل تفتفة أو ضعف أو صرفية غير طبيعية؟",
            [
                "إي",
                "لا",
                "ما متأكد"
            ],
            f"{code}_maf_symptoms"
        )

        if symptom == "إي":

            result(
                "الأعراض مهمة",
                "حدد متى تظهر الأعراض: خمول، دعس، حمل أو RPM معين."
            )

        recurrence = ask(
            8,
            "بعد مسح الكود وتجربة السيارة، يرجع نفس الكود؟",
            [
                "إي",
                "لا"
            ],
            f"{code}_maf_recurrence"
        )

        if recurrence == "لا":

            result(
                "الكود ما رجع",
                "راقب السيارة بظروف تشغيل مختلفة."
            )
            return

