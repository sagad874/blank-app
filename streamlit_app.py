def step(n,q):
    st.markdown(f"<div style='background:#222;color:white;padding:9px;border-radius:9px;text-align:center;font-weight:bold'>الخطوة {n}</div>",unsafe_allow_html=True)
    st.markdown(f"<div dir='rtl' style='font-size:18px;padding:10px'>🔧 {q}</div>",unsafe_allow_html=True)

def ask(n,q,o,k):
    step(n,q)
    return st.radio("شنو النتيجة؟",o,key=k)

def msg(t,x,kind="success"):
    getattr(st,{"success":"success","warning":"warning","error":"error"}.get(kind,"success"))(f"**{t}**\n\n{x}")

